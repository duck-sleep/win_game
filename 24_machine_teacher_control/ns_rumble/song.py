"""简谱 → Hz。八度 4 时 1=C4（A4=440，十二平均律）。"""

from __future__ import annotations

# 简谱 1–7 → C 大调半音数
SEMITONE = {1: 0, 2: 2, 3: 4, 4: 5, 5: 7, 6: 9, 7: 11}
NAME = {1: "C", 2: "D", 3: "E", 4: "F", 5: "G", 6: "A", 7: "B"}


def degree_hz(degree: int, octave: int = 4) -> float:
    # A4 = 440 Hz；C4 = 440 * 2**(-9/12) = 261.63
    return 440.0 * 2.0 ** ((SEMITONE[degree] - 9 + 12 * (octave - 4)) / 12.0)


